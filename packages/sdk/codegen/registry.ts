import { registryOverrides } from "./facade-overrides";
import { toCase } from "./promise-naming";
import { expectRecord, expectArray } from "./promise-schema";

export const registryHeader = "// Generated by codegen/generate-registry.ts. Do not edit.\n";

export const generateRegistry = (input: unknown, overrides = registryOverrides) => {
  const document = expectRecord(input, "OpenAPI");
  const { facadeAliases } = overrides;
  type ValueOverrides = Omit<typeof overrides, "facadeAliases">;
  const consumed = new Map<string, Set<string>>();
  const consumedAliases = new Set<string>();
  const useOverride = (table: keyof ValueOverrides, key: string): string | undefined => {
    const value = overrides[table][key];
    if (value !== undefined) {
      const keys = consumed.get(table) ?? new Set<string>();
      keys.add(key);
      consumed.set(table, keys);
    }
    return value;
  };
  const services: Record<string, Record<string, string>> = {};
  const serviceFilenames: Record<string, string> = {};
  const calls: Record<string, { kind: string; paths?: string[] }> = {};
  const methods = new Set(["get", "post", "put", "patch", "delete", "options", "head", "trace"]);
  for (const [path, item] of Object.entries(expectRecord(document.paths, "paths"))) {
    for (const [method, value] of Object.entries(expectRecord(item, path))) {
      if (!methods.has(method)) continue;
      const operation = expectRecord(value, `${method} ${path}`);
      if (typeof operation.operationId !== "string")
        throw new Error(`Missing operationId: ${method} ${path}`);
      const [group, name, ...rest] = operation.operationId.split(".");
      if (!group || !name || rest.length)
        throw new Error(`Invalid operationId: ${operation.operationId}`);
      const id = toCase(operation.operationId, "camelCase");
      const service = useOverride("facadeServiceOverrides", group) ?? group;
      const operations = (services[service] ??= {});
      if (Object.hasOwn(operations, name))
        throw new Error(
          `Facade operation collision: ${service}.${name} (${operations[name]}, ${id})`,
        );
      operations[name] = id;
      if (Object.hasOwn(calls, id)) throw new Error(`Operation ID collision: ${id}`);
      if (group === service) {
        const tag = expectArray(operation.tags, `${id} tags`)[0];
        if (typeof tag !== "string") throw new Error(`Missing group tag: ${id}`);
        const filename = tag
          .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
          .replace(/[^a-zA-Z0-9]+/g, "-")
          .toLowerCase();
        if (serviceFilenames[service] !== undefined && serviceFilenames[service] !== filename)
          throw new Error(`Conflicting group tags: ${service}`);
        serviceFilenames[service] = filename;
      }
      const parameters =
        operation.parameters === undefined
          ? []
          : expectArray(operation.parameters, id).map((parameter) => expectRecord(parameter, id));
      const paths = parameters
        .filter((parameter) => parameter.in === "path")
        .map((parameter) => {
          if (typeof parameter.name !== "string") throw new Error(`Unnamed path parameter: ${id}`);
          return parameter.name;
        });
      const query = parameters.some((parameter) => parameter.in === "query");
      const payload = operation.requestBody !== undefined;
      if (query && payload) throw new Error(`Unsupported query and payload combination: ${id}`);
      const contentKind = payload ? "payload" : query ? "params" : "none";
      const pathKinds = { payload: "pathPayload", params: "pathParams", none: "path" };
      const kind = paths.length ? pathKinds[contentKind] : contentKind;
      const override = useOverride("callKindOverrides", id);
      calls[id] = {
        kind: override ?? kind,
        ...(paths.length || override ? { paths } : {}),
      };
    }
  }
  for (const [service, aliases] of Object.entries(facadeAliases)) {
    const operations = services[service];
    if (operations === undefined) throw new Error(`Unused facadeAliases service: ${service}`);
    for (const [name, id] of Object.entries(aliases)) {
      if (Object.hasOwn(operations, name))
        throw new Error(`Facade alias collision: ${service}.${name}`);
      if (!Object.hasOwn(calls, id))
        throw new Error(`Unknown facade alias target: ${service}.${name} -> ${id}`);
    }
    services[service] = { ...aliases, ...operations };
    consumedAliases.add(service);
  }
  const modules: Record<string, { service: string; promisePath: string }> = {};
  for (const service of Object.keys(services)) {
    const filename = useOverride("facadeModuleNames", service) ?? serviceFilenames[service];
    if (filename === undefined) throw new Error(`Missing group filename: ${service}`);
    if (Object.hasOwn(modules, filename)) throw new Error(`Facade module collision: ${filename}`);
    modules[filename] = {
      service,
      promisePath: useOverride("facadePromisePaths", service) ?? service,
    };
  }
  const sharedCalls: Readonly<Record<string, string>> = {
    path: "idPath",
    pathPayload: "idPathPayload",
    pathParams: "idPathParams",
  };
  const callEntries = Object.entries(calls).map(([id, call]) => {
    const shared =
      call.paths?.length === 1 && call.paths[0] === "id" ? sharedCalls[call.kind] : undefined;
    return `${JSON.stringify(id)}: ${shared ?? JSON.stringify(call)}`;
  });
  const sharedDeclarations = Object.entries(sharedCalls)
    .map(
      ([kind, name]) =>
        `const ${name} = { kind: ${JSON.stringify(kind)}, paths: ["id"] } as const;`,
    )
    .join("\n");
  const header = registryHeader;
  const registrySource =
    `${header}/**\n * Explicit mapping between the public SDK facade and generated Effect client\n * operations. This is intentionally data rather than codegen so facade drift\n * is visible in review and test failures.\n */\nexport const SDK_SERVICE_OPERATIONS = ${JSON.stringify(services, null, 2)} as const;\n${sharedDeclarations}\n/** How each generated Effect operation is adapted to the Promise facade's direct input shape. */\nexport const SDK_OPERATION_CALLS = {${callEntries.join(",\n")}} as const;\n` +
    `export const SDK_EFFECT_MODULES = ${JSON.stringify(Object.fromEntries(Object.entries(modules).map(([filename, module]) => [filename, module.service])), null, 2)} as const;\n`;
  const domainSources = Object.entries(services).map(([service, operations]) => {
    const schemaFilename = serviceFilenames[service];
    const filename = useOverride("facadeModuleNames", service) ?? schemaFilename;
    if (filename === undefined) throw new Error(`Missing group filename: ${service}`);
    const groupName = useOverride("facadeGroupNames", service) ?? toCase(service, "PascalCase");
    const preamble = `import { ${groupName}Group } from "./generated/${schemaFilename}";\nimport { forGroup } from "./internal/operation";\n${useOverride("facadePreambles", filename) ?? ""}\nconst make = /* @__PURE__ */ forGroup(${groupName}Group);`;
    const declarations = Object.entries(operations).map(([name, id]) => {
      const expression =
        useOverride(
          "facadeExpressions",
          `${service}${name.charAt(0).toUpperCase()}${name.slice(1)}`,
        ) ??
        useOverride("facadeExpressions", id) ??
        `/* @__PURE__ */ make(${JSON.stringify(id)})`;
      const localName = useOverride("reservedOperationNames", id) ?? `${name}Operation`;
      return name === "export" || name === "delete"
        ? `const ${localName} = ${expression};\nexport { ${localName} as ${name} };`
        : `export const ${name} = ${expression};`;
    });
    return [filename, `${header}${preamble}\n\n${declarations.join("\n")}\n`] as const;
  });

  for (const [table, values] of Object.entries(overrides)) {
    const used = table === "facadeAliases" ? consumedAliases : consumed.get(table);
    for (const key of Object.keys(values)) {
      if (!used?.has(key)) throw new Error(`Unused ${table} override: ${key}`);
    }
  }
  return {
    services,
    calls,
    modules,
    registrySource,
    moduleSources: Object.fromEntries(domainSources),
  };
};
