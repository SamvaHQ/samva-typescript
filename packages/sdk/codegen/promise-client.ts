export const generatePromiseClientSources = (document: unknown): PromiseClientSources => {
  if (!isRecord(document)) throw new Error("The OpenAPI document must be an object");
  const parsed = parseDocument(document);
  const split = splitReadWrite(
    parsed.schemas,
    parsed.operations.flatMap(requestSchemas),
    parsed.operations.flatMap(({ responses }) => Object.values(responses)),
  );
  const retargeted = {
    ...parsed,
    operations: parsed.operations.map((operation) => retargetOperation(operation, split.retarget)),
  };
  const types = renderTypes(retargeted, split.schemas);
  return {
    types: types.source,
    sdk: renderSdk(retargeted, types.operations),
    client: renderClient(parsed.servers),
  };
};
