const assertName = (name: string, reserved: ReadonlySet<string>, context: string): string => {
  if (!identifierName.test(name) || reserved.has(name)) {
    throw new Error(`${context} name "${name}" is not a usable identifier`);
  }
  return name;
};

/** Hands out file-level names, suffixing `2`, `3`, … when a name is already taken. */
class NameScope {
  readonly #taken = new Set<string>();

  claim(name: string): string {
    let candidate = name;
    for (let attempt = 1; this.#taken.has(candidate); attempt++)
      candidate = `${name}${attempt + 1}`;
    this.#taken.add(candidate);
    return candidate;
  }
}

interface OperationTypeNames {
  readonly data: string;
  readonly errors: string | undefined;
  readonly error: string | undefined;
  readonly responses: string | undefined;
  readonly response: string | undefined;
}

