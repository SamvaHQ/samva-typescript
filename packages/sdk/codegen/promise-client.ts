/**
 * OpenAPI 3.1 → the Promise client's spec-derived sources: `types.gen.ts`, `sdk.gen.ts`, and
 * `client.gen.ts` under `src/client`.
 *
 * The fetch runtime those files import (`src/client/client/**`, `src/client/core/**`) is vendored
 * source and is not written here. The emitted shape is the public Promise SDK: one class per tag
 * whose static methods take flat parameters, plus `*Data`/`*Errors`/`*Error`/`*Responses`/
 * `*Response` types per operation. Optional members are emitted as `key?: T | undefined` so
 * consumers compiled with exactOptionalPropertyTypes can pass possibly-undefined values; the
 * direct members of `*Data` envelopes stay exact-optional because they are assigned into the
 * runtime's exact-optional request options. Types a caller writes also admit `undefined` in record
 * entries; `promise-readwrite.ts` gives schemas shared with responses a `Writable` variant for
 * that. Unsupported OpenAPI features fail generation.
 */

