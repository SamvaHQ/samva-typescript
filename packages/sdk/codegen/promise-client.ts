// Request position

/** Every schema a caller writes: the body and each parameter. */
const requestSchemas = ({ body, parameters }: Operation): Array<Ir> => [
  ...(body === undefined ? [] : [body.schema]),
  ...[...parameters.header, ...parameters.path, ...parameters.query].map(({ schema }) => schema),
];

/** The operation with the schemas a caller writes pointing at their write variants. */
const retargetOperation = (operation: Operation, retarget: (schema: Ir) => Ir): Operation => {
  const parameters = (list: ReadonlyArray<Parameter>) =>
    list.map((parameter) => ({ ...parameter, schema: retarget(parameter.schema) }));
  return {
    ...operation,
    parameters: {
      header: parameters(operation.parameters.header),
      path: parameters(operation.parameters.path),
      query: parameters(operation.parameters.query),
    },
    body:
      operation.body === undefined
        ? undefined
        : { ...operation.body, schema: retarget(operation.body.schema) },
  };
};

