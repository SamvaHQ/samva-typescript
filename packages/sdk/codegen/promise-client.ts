// Operations

/** Path item methods in emission order. */
const methods = ["delete", "get", "head", "options", "patch", "post", "put", "trace"] as const;
type Method = (typeof methods)[number];

type ParameterLocation = "header" | "path" | "query";

interface Parameter {
  readonly name: string;
  readonly location: ParameterLocation;
  readonly required: boolean;
  readonly schema: Ir;
}

interface Body {
  readonly schema: Ir;
  /** Component the body schema names, which a flat parameter is named after. */
  readonly ref: string | undefined;
  readonly mediaType: string;
  readonly required: boolean;
}

interface AuthObject {
  readonly [key: string]: string;
}

interface Operation {
  /** camelCase operation identifier; base of the per-operation type names. */
  readonly id: string;
  readonly method: Method;
  readonly path: string;
  readonly tag: string;
  readonly segments: ReadonlyArray<string>;
  readonly summary: string | undefined;
  readonly description: string | undefined;
  readonly deprecated: boolean;
  readonly parameters: Readonly<Record<ParameterLocation, ReadonlyArray<Parameter>>>;
  readonly body: Body | undefined;
  /** Keyed by status code; integer keys enumerate in ascending order. */
  readonly responses: Readonly<Record<string, Ir>>;
  readonly security: ReadonlyArray<AuthObject>;
}

const allowedKeys = (record: JsonRecord, allowed: ReadonlyArray<string>, context: string) => {
  for (const key of Object.keys(record)) {
    if (!key.startsWith("x-") && !allowed.includes(key)) {
      throw new Error(`Unsupported key "${key}" at ${context}`);
    }
  }
};

interface MediaContent {
  readonly mediaType: string;
  readonly schema: unknown;
}

const jsonContent = (value: unknown, context: string): MediaContent => {
  const entries = Object.entries(expectRecord(value, context));
  const [first] = entries;
  if (entries.length !== 1 || first === undefined || !/^application\/json$/i.test(first[0])) {
    throw new Error(`Only a single application/json media type is supported at ${context}`);
  }
  const [mediaType, mediaValue] = first;
  const media = expectRecord(mediaValue, `${context}.${mediaType}`);
  allowedKeys(media, ["schema"], `${context}.${mediaType}`);
  return { mediaType, schema: media["schema"] };
};

// Keeps the fields of an annotated wrapper ({ description, ...schema }) in spread order.
const withDescription = (description: string | undefined, schema: unknown, context: string) => {
  const record = expectRecord(schema, context);
  return description === undefined ? { ...record } : { description, ...record };
};

const sanitizeOperationId = (value: string): string =>
  value
    .replace(/^[^\p{ID_Start}]+/u, "")
    .replace(/[^$\u200c\u200d\p{ID_Continue}]/gu, "-")
    .replace(/[$+]/g, "-");

const authObject = (scheme: JsonRecord, context: string): AuthObject => {
  const type = optionalString(scheme, "type", context);
  if (type === "apiKey") {
    const name = optionalString(scheme, "name", context);
    const location = optionalString(scheme, "in", context);
    if (name === undefined) throw new Error(`${context}.name is required`);
    if (location === "header") return { name, type: "apiKey" };
    if (location === "query" || location === "cookie")
      return { in: location, name, type: "apiKey" };
    throw new Error(`Unsupported apiKey location at ${context}`);
  }
  if (type === "http") {
    const httpScheme = optionalString(scheme, "scheme", context)?.toLowerCase();
    if (httpScheme === "bearer" || httpScheme === "basic") {
      return { scheme: httpScheme, type: "http" };
    }
  }
  throw new Error(`Unsupported security scheme at ${context}`);
};

interface ParsedDocument {
  readonly servers: ReadonlyArray<string>;
  readonly schemas: ReadonlyArray<readonly [string, Ir]>;
  readonly operations: ReadonlyArray<Operation>;
}

const parseDocument = (input: unknown): ParsedDocument => {
  const document = expectRecord(input, "document");
  // `webhooks` describes what Samva sends, not what a client calls; `@samva/webhooks` owns it.
  allowedKeys(
    document,
    ["openapi", "info", "servers", "paths", "webhooks", "components", "tags", "security"],
    "document",
  );
  const version = optionalString(document, "openapi", "document");
  if (version === undefined || !version.startsWith("3.1.")) {
    throw new Error(`Only OpenAPI 3.1 documents are supported (got ${String(version)})`);
  }
  const documentSecurity = document["security"];
  if (documentSecurity !== undefined && expectArray(documentSecurity, "security").length > 0) {
    throw new Error("Document-level security requirements are unsupported");
  }

  const servers = expectArray(document["servers"] ?? [], "servers").map((server, index) => {
    const record = expectRecord(server, `servers[${index}]`);
    allowedKeys(record, ["url", "description"], `servers[${index}]`);
    const url = optionalString(record, "url", `servers[${index}]`);
    if (url === undefined || !URL.canParse(url) || new URL(url).host === "") {
      throw new Error(`servers[${index}].url must be an absolute URL`);
    }
    return url;
  });

  const components = expectRecord(document["components"] ?? {}, "components");
  allowedKeys(components, ["schemas", "securitySchemes", "parameters", "responses"], "components");
  for (const key of ["parameters", "responses"]) {
    if (Object.keys(expectRecord(components[key] ?? {}, `components.${key}`)).length > 0) {
      throw new Error(`components.${key} is unsupported`);
    }
  }
  const schemas = Object.entries(expectRecord(components["schemas"] ?? {}, "schemas")).map(
    ([name, schema]): readonly [string, Ir] => [
      name,
      schemaToIr(schema, `#/components/schemas/${name}`),
    ],
  );
  const securitySchemes = expectRecord(components["securitySchemes"] ?? {}, "securitySchemes");
  if (Object.keys(securitySchemes).length > 1) {
    throw new Error("Multiple security schemes are unsupported");
  }

  const ids = new Set<string>();
  const operations: Array<Operation> = [];
  for (const [path, pathItemValue] of Object.entries(expectRecord(document["paths"], "paths"))) {
    const pathItem = expectRecord(pathItemValue, `paths.${path}`);
    allowedKeys(pathItem, methods, `paths.${path}`);
    for (const method of methods) {
      if (pathItem[method] === undefined) continue;
      const context = `${method.toUpperCase()} ${path}`;
      const operation = parseOperation(pathItem[method], method, path, securitySchemes, context);
      if (ids.has(operation.id)) throw new Error(`Duplicate operation id ${operation.id}`);
      ids.add(operation.id);
      operations.push(operation);
    }
  }
  return { servers, schemas, operations };
};

const parseOperation = (
  value: unknown,
  method: Method,
  path: string,
  securitySchemes: JsonRecord,
  context: string,
): Operation => {
  const operation = expectRecord(value, context);
  allowedKeys(
    operation,
    [
      "operationId",
      "summary",
      "description",
      "deprecated",
      "tags",
      "parameters",
      "requestBody",
      "responses",
      "security",
    ],
    context,
  );
  const operationId = optionalString(operation, "operationId", context);
  if (operationId === undefined) throw new Error(`${context} has no operationId`);
  const segments = operationId.split(/[./]/).filter(Boolean);
  if (segments.length === 0) throw new Error(`${context} has an empty operationId`);
  const tags = expectArray(operation["tags"] ?? [], `${context}.tags`);
  const [tag] = tags;
  if (tags.length !== 1 || typeof tag !== "string" || tag.length === 0) {
    throw new Error(`${context} must have exactly one tag`);
  }

  const parameters: Record<ParameterLocation, Array<Parameter>> = {
    header: [],
    path: [],
    query: [],
  };
  const seen = new Set<string>();
  expectArray(operation["parameters"] ?? [], `${context}.parameters`).forEach((entry, index) => {
    const parameterContext = `${context}.parameters[${index}]`;
    const parameter = expectRecord(entry, parameterContext);
    allowedKeys(parameter, ["name", "in", "required", "schema", "description"], parameterContext);
    const name = optionalString(parameter, "name", parameterContext);
    const location = optionalString(parameter, "in", parameterContext);
    if (name === undefined) throw new Error(`${parameterContext}.name is required`);
    if (location !== "header" && location !== "path" && location !== "query") {
      throw new Error(`Unsupported parameter location ${String(location)} at ${parameterContext}`);
    }
    const key = `${location}:${name.toLocaleLowerCase()}`;
    if (seen.has(key) || /^-?\d+(\.\d+)?$/.test(name)) {
      throw new Error(`Unsupported parameter name ${name} at ${parameterContext}`);
    }
    seen.add(key);
    const schema = schemaToIr(
      withDescription(
        optionalString(parameter, "description", parameterContext),
        parameter["schema"],
        `${parameterContext}.schema`,
      ),
      `${parameterContext}.schema`,
    );
    if (location === "query" && schema.type === "object") {
      throw new Error(`Object query parameters are unsupported at ${parameterContext}`);
    }
    parameters[location].push({
      name,
      location,
      required: parameter["required"] === true,
      schema,
    });
  });

  let body: Body | undefined;
  if (operation["requestBody"] !== undefined) {
    const requestBody = expectRecord(operation["requestBody"], `${context}.requestBody`);
    allowedKeys(requestBody, ["content", "required", "description"], `${context}.requestBody`);
    const content = jsonContent(requestBody["content"], `${context}.requestBody.content`);
    const schema = schemaToIr(
      withDescription(
        optionalString(requestBody, "description", `${context}.requestBody`),
        content.schema,
        `${context}.requestBody`,
      ),
      `${context}.requestBody`,
    );
    body = {
      schema,
      ref: schema.$ref === undefined ? undefined : refToName(schema.$ref),
      mediaType: content.mediaType,
      required: requestBody["required"] === true,
    };
  }

  const responses: Record<string, Ir> = {};
  for (const [status, responseValue] of Object.entries(
    expectRecord(operation["responses"], `${context}.responses`),
  )) {
    if (!/^[1-5]\d\d$/.test(status)) {
      throw new Error(`Unsupported response status ${status} at ${context}`);
    }
    const responseContext = `${context}.responses.${status}`;
    const response = expectRecord(responseValue, responseContext);
    allowedKeys(response, ["description", "content"], responseContext);
    responses[status] = schemaToIr(
      withDescription(
        optionalString(response, "description", responseContext),
        jsonContent(response["content"], `${responseContext}.content`).schema,
        responseContext,
      ),
      responseContext,
    );
  }

  const security = new Map<string, AuthObject>();
  expectArray(operation["security"] ?? [], `${context}.security`).forEach((requirement) => {
    for (const name of Object.keys(expectRecord(requirement, `${context}.security`))) {
      const scheme = securitySchemes[name];
      if (scheme === undefined) throw new Error(`${context} uses undeclared security ${name}`);
      security.set(name, authObject(expectRecord(scheme, name), `securitySchemes.${name}`));
    }
  });

  return {
    id: toCase(sanitizeOperationId(operationId), "camelCase"),
    method,
    path,
    tag,
    segments,
    summary: optionalString(operation, "summary", context),
    description: optionalString(operation, "description", context),
    deprecated: operation["deprecated"] === true,
    parameters,
    body,
    responses,
    security: [...security.values()],
  };
};

