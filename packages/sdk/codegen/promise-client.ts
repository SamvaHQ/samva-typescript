interface SignatureField {
  readonly in?: "body" | "headers" | "path" | "query";
  readonly key: string;
  readonly map?: string;
}

interface Signature {
  readonly required: boolean;
  readonly members: ReadonlyArray<ObjectMember>;
  readonly fields: ReadonlyArray<SignatureField>;
  readonly wholeBody?: TypeNode;
}

// Flat SDK parameters: every path/query/header parameter and top-level body property becomes a
// field of one `parameters` object; names used in more than one location get a location prefix.
const signature = (
  operation: Operation,
  onReference: (typeName: string) => void,
): Signature | undefined => {
  const locations = ["header", "path", "query"] as const;
  const body = operation.body;
  // A discriminated object union is already a flat request. Flattening its members separately
  // loses their relationship; wrapping it adds a field that the HTTP contract does not have.
  if (
    body !== undefined &&
    body.schema.logicalOperator === "or" &&
    body.schema.items?.every((item) => item.type === "object") &&
    locations.every((location) => operation.parameters[location].length === 0)
  ) {
    return {
      required: body.required,
      members: [],
      fields: [],
      wholeBody: schemaToType(body.schema, onReference),
    };
  }
  const flattenBody =
    body !== undefined &&
    body.schema.logicalOperator === undefined &&
    body.schema.type === "object" &&
    body.schema.properties !== undefined;
  const refBodyName = body?.ref === undefined ? undefined : toCase(body.ref, "camelCase");

  const locationsByName = new Map<string, Set<string>>();
  const note = (name: string, location: string) => {
    const set = locationsByName.get(name) ?? new Set<string>();
    set.add(location);
    locationsByName.set(name, set);
  };
  for (const location of locations) {
    for (const parameter of operation.parameters[location]) note(parameter.name, location);
  }
  if (body !== undefined) {
    if (flattenBody)
      for (const name of Object.keys(body.schema.properties ?? {})) note(name, "body");
    else note(refBodyName ?? "body", "body");
  }
  const conflicted = (name: string) => (locationsByName.get(name)?.size ?? 0) > 1;

  const members: Array<ObjectMember> = [];
  const fields: Array<SignatureField> = [];
  let required = false;
  const add = (name: string, isRequired: boolean, schema: Ir, field: SignatureField) => {
    if (isRequired) required = true;
    members.push({
      kind: "property",
      name,
      optional: !isRequired,
      doc: [],
      type: schemaToType(schema, onReference),
    });
    fields.push(field);
  };
  for (const location of locations) {
    for (const parameter of operation.parameters[location]) {
      const name = conflicted(parameter.name) ? `${location}_${parameter.name}` : parameter.name;
      const fieldIn = location === "header" ? "headers" : location;
      add(
        name,
        parameter.required,
        parameter.schema,
        name === parameter.name
          ? { in: fieldIn, key: name }
          : { in: fieldIn, key: name, map: parameter.name },
      );
    }
  }
  if (body !== undefined) {
    if (flattenBody) {
      const bodyRequired = body.schema.required ?? [];
      for (const [original, property] of Object.entries(body.schema.properties ?? {})) {
        const name = conflicted(original) ? `body_${original}` : original;
        add(
          name,
          bodyRequired.includes(original),
          property,
          name === original ? { in: "body", key: name } : { in: "body", key: name, map: original },
        );
      }
    } else {
      const original = refBodyName ?? "body";
      const name =
        refBodyName !== undefined && conflicted(original) ? `body_${original}` : original;
      add(name, body.required, body.schema, { key: name, map: "body" });
    }
  }
  if (members.length === 0) return undefined;
  return { required, members, fields };
};

/** Object literal text; objects with three or more entries are written one entry per line. */
const objectLiteral = (entries: ReadonlyArray<string>, multiline = entries.length >= 3): string => {
  if (entries.length === 0) return "{}";
  return multiline ? `{\n${entries.join(",\n")},\n}` : `{ ${entries.join(", ")} }`;
};

const fieldLiteral = (field: SignatureField): string =>
  objectLiteral([
    ...(field.in === undefined ? [] : [`in: ${JSON.stringify(field.in)}`]),
    `key: ${JSON.stringify(field.key)}`,
    ...(field.map === undefined ? [] : [`map: ${JSON.stringify(field.map)}`]),
  ]);

const authLiteral = (auth: AuthObject): string =>
  objectLiteral(
    Object.entries(auth).map(([key, value]) => `${propertyKey(key)}: ${JSON.stringify(value)}`),
  );

/** Final local names in sdk.gen.ts, after conflicts with local declarations are resolved. */
interface SdkNames {
  /** Client runtime import (`Options`, `RequestResult`, `buildClientParams`, …). */
  readonly runtime: (name: string) => string;
  /** Import from types.gen.ts. */
  readonly type: (name: string) => string;
  readonly client: string;
  readonly options: string;
}

interface SdkMethod {
  readonly operation: Operation;
  readonly name: string;
  readonly signature: Signature | undefined;
  readonly referencedTypes: ReadonlyArray<string>;
}

interface ClassNode {
  readonly name: string;
  readonly children: Map<string, ClassNode>;
  readonly methods: Array<SdkMethod>;
  /** Name before file-level conflict suffixing; the holder's member is named after it. */
  requestedName: string;
  className: string;
}

const renderMethod = (
  method: SdkMethod,
  typeNames: OperationTypeNames,
  names: SdkNames,
): string => {
  const { operation } = method;
  const responses = typeNames.responses === undefined ? "unknown" : names.type(typeNames.responses);
  const errors = typeNames.errors === undefined ? "unknown" : names.type(typeNames.errors);
  const generics = `${responses}, ${errors}, ThrowOnError`;
  const doc: Array<string> = [];
  const push = (line: string) => {
    if (doc.length > 0) doc.push("");
    doc.push(line);
  };
  for (const line of [operation.summary, operation.description]) {
    if (line) push(escapeComment(line));
  }
  if (operation.deprecated) push("@deprecated");

  const parameters: Array<string> = [];
  const statements: Array<string> = [];
  const request = [
    ...(operation.security.length === 0
      ? []
      : [`security: [${operation.security.map(authLiteral).join(", ")}]`]),
    `url: ${JSON.stringify(operation.path)}`,
    "...options",
  ];
  if (method.signature !== undefined) {
    const parametersType = printType(
      method.signature.wholeBody ?? { kind: "object", members: method.signature.members },
      { loosenOptionals: true, loosenRecords: true, resolveReference: names.type },
      "    ",
    );
    parameters.push(`parameters${method.signature.required ? "" : "?"}: ${parametersType}`);
    const args = `[${method.signature.fields.map(fieldLiteral).join(", ")}]`;
    statements.push(
      method.signature.wholeBody === undefined
        ? `const params = ${names.runtime("buildClientParams")}([parameters], [${objectLiteral([`args: ${args}`])}]);`
        : "const params = { body: parameters };",
    );
    request.push("...params");
  }
  if (
    operation.body?.required &&
    operation.body.schema.type === "object" &&
    operation.body.schema.logicalOperator === undefined
  ) {
    request.push(method.signature === undefined ? "body: {}" : "body: params.body ?? {}");
  }
  if (operation.body !== undefined) {
    const contentType = operation.parameters.header.find(
      (parameter) => parameter.name.toLocaleLowerCase() === "content-type",
    );
    if (contentType === undefined || !contentType.required) {
      request.push(
        `headers: ${objectLiteral(
          [
            `${propertyKey(contentType?.name ?? "Content-Type")}: ${JSON.stringify(operation.body.mediaType)}`,
            "...options?.headers",
            ...(method.signature === undefined ? [] : ["...params.headers"]),
          ],
          true,
        )}`,
      );
    }
  }
  parameters.push(`options?: ${names.options}<never, ThrowOnError>`);
  statements.push(
    `return (options?.client ?? ${names.client}).${operation.method}<${generics}>(${objectLiteral(request)});`,
  );
  return [
    `${docComment(doc, "  ")}  public static ${method.name}<ThrowOnError extends boolean = false>(`,
    ...parameters.map((parameter) => `    ${parameter},`),
    `  ): ${names.runtime("RequestResult")}<${generics}> {`,
    ...statements.map((statement) => `    ${statement}`),
    "  }",
  ].join("\n");
};

const renderSdk = (
  parsed: ParsedDocument,
  typeNames: ReadonlyMap<Operation, OperationTypeNames>,
): string => {
  // Class tree: one root per tag, one nested class per operationId segment.
  const roots = new Map<string, ClassNode>();
  const methodsInOrder: Array<SdkMethod> = [];
  if (parsed.operations.length === 0) throw new Error("The OpenAPI document has no operations");
  for (const operation of parsed.operations) {
    const referencedTypes: Array<string> = [];
    const method: SdkMethod = {
      operation,
      name: assertName(
        toCase(operation.segments.at(-1) ?? "", "camelCase"),
        new Set(),
        `${operation.id} method`,
      ),
      signature: signature(operation, (name) => referencedTypes.push(name)),
      referencedTypes,
    };
    let node = roots.get(operation.tag);
    if (node === undefined) {
      node = {
        name: operation.tag,
        children: new Map(),
        methods: [],
        requestedName: "",
        className: "",
      };
      roots.set(operation.tag, node);
    }
    for (const segment of operation.segments.slice(0, -1)) {
      let child: ClassNode | undefined = node.children.get(segment);
      if (child === undefined) {
        child = {
          name: segment,
          children: new Map(),
          methods: [],
          requestedName: "",
          className: "",
        };
        node.children.set(segment, child);
      }
      node = child;
    }
    node.methods.push(method);
    methodsInOrder.push(method);
  }

  // Post-order: nested classes are declared (and named) before the class that holds them.
  const classes: Array<ClassNode> = [];
  const visit = (node: ClassNode) => {
    for (const child of node.children.values()) visit(child);
    classes.push(node);
  };
  for (const root of roots.values()) visit(root);

  const scope = new NameScope();
  const localOptions = scope.claim("Options");
  const rootNodes = new Set(roots.values());
  for (const node of classes) {
    const base = rootNodes.has(node) ? node.name.toLowerCase() : node.name;
    node.requestedName = assertName(toCase(base, "PascalCase"), reservedRuntimeNames, "Class");
    node.className = scope.claim(node.requestedName);
  }

  // Imports take the names left over by local declarations, in first-use order.
  const hasParams = methodsInOrder.some((method) => method.signature !== undefined);
  const runtimeImports = ["Options", "TDataShape", "Client", "ClientMeta", "RequestResult"];
  if (hasParams) runtimeImports.push("buildClientParams");
  const runtime = new Map(runtimeImports.map((name) => [name, scope.claim(name)]));
  const clientName = scope.claim("client");
  const typeImports = new Map<string, string>();
  const operationNames = (operation: Operation): OperationTypeNames => {
    const found = typeNames.get(operation);
    if (found === undefined) throw new Error(`Missing types for ${operation.id}`);
    return found;
  };
  for (const method of methodsInOrder) {
    const { responses, errors } = operationNames(method.operation);
    const used = [
      ...method.referencedTypes,
      ...(responses === undefined ? [] : [responses]),
      ...(errors === undefined ? [] : [errors]),
    ];
    for (const name of used) {
      if (runtime.has(name)) throw new Error(`Type ${name} collides with a client runtime import`);
      if (!typeImports.has(name)) typeImports.set(name, scope.claim(name));
    }
  }
  const planned = (imports: ReadonlyMap<string, string>, kind: string) => (name: string) => {
    const resolved = imports.get(name);
    if (resolved === undefined) throw new Error(`${kind} import ${name} was not planned`);
    return resolved;
  };
  const names: SdkNames = {
    runtime: planned(runtime, "Runtime"),
    type: planned(typeImports, "Type"),
    client: clientName,
    options: localOptions,
  };

  const specifier = (source: string, local: string, typeOnly: boolean) =>
    `${typeOnly ? "type " : ""}${source === local ? local : `${source} as ${local}`}`;
  const byLocalName = (left: readonly [string, string], right: readonly [string, string]) =>
    left[1].localeCompare(right[1], "en");
  const runtimeTypeOnly = !runtime.has("buildClientParams");
  const runtimeSpecifiers = [...runtime.entries()]
    .sort(byLocalName)
    .map(([source, local]) =>
      specifier(source, local, !runtimeTypeOnly && source !== "buildClientParams"),
    );
  const typeSpecifiers = [...typeImports.entries()]
    .sort(byLocalName)
    .map(([source, local]) => specifier(source, local, false));

  const imports = [
    `import ${runtimeTypeOnly ? "type " : ""}{ ${runtimeSpecifiers.join(", ")} } from "./client";`,
    `import { ${clientName === "client" ? "client" : `client as ${clientName}`} } from "./client.gen";`,
    ...(typeSpecifiers.length === 0
      ? []
      : [`import type { ${typeSpecifiers.join(", ")} } from "./types.gen";`]),
  ];

  const optionsType = [
    `export type ${localOptions}<`,
    `  TData extends ${names.runtime("TDataShape")} = ${names.runtime("TDataShape")},`,
    "  ThrowOnError extends boolean = boolean,",
    "  TResponse = unknown,",
    `> = ${names.runtime("Options")}<TData, ThrowOnError, TResponse> & {`,
    "  /**",
    "   * You can provide a client instance returned by `createClient()` instead of",
    "   * individual options. This might be also useful if you want to implement a",
    "   * custom client.",
    "   */",
    `  client?: ${names.runtime("Client")} | undefined;`,
    "  /**",
    "   * You can pass arbitrary values through the `meta` object. This can be",
    "   * used to access values that aren't defined as part of the SDK function.",
    "   */",
    `  meta?: (keyof ${names.runtime("ClientMeta")} extends never ? Record<string, unknown> : ${names.runtime("ClientMeta")}) | undefined;`,
    "};",
  ].join("\n");

  const classSources = classes.map((node) => {
    const members = node.methods.map((method) =>
      renderMethod(method, operationNames(method.operation), names),
    );
    for (const child of node.children.values()) {
      members.push(`  static ${toCase(child.requestedName, "camelCase")} = ${child.className};`);
    }
    return `export class ${node.className} {\n${members.join("\n\n")}\n}`;
  });

  return `// @ts-nocheck\n${GENERATED_HEADER}\n\n${imports.join("\n")}\n\n${[optionsType, ...classSources].join("\n\n")}\n`;
};

