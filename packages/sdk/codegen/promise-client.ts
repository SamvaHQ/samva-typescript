interface OperationTypes {
  readonly names: OperationTypeNames;
  readonly declarations: ReadonlyArray<string>;
}

const typeAlias = (
  name: string,
  type: TypeNode,
  doc: ReadonlyArray<string>,
  looseMembers = true,
  loosenRecords = false,
): string =>
  `${docComment(doc, "")}export type ${name} = ${printType(type, { loosenOptionals: true, loosenRecords }, "", looseMembers)};`;

const parametersToIr = (parameters: ReadonlyArray<Parameter>): Ir => {
  const ir: Ir = {
    type: "object",
    properties: Object.fromEntries(
      parameters.map((parameter) => [parameter.name, deduplicate(parameter.schema, false)]),
    ),
  };
  const required = parameters.filter((parameter) => parameter.required).map(({ name }) => name);
  if (required.length > 0) ir.required = required;
  return ir;
};

// Union of every response schema in a group; `undefined` when it carries no type information.
const responseUnion = (schemas: ReadonlyArray<Ir>): Ir | undefined => {
  const [only] = schemas;
  const merged: Ir =
    schemas.length === 1 && only !== undefined
      ? { ...only }
      : { items: [...schemas], logicalOperator: "or" };
  const deduplicated = deduplicate(merged);
  if (Object.keys(deduplicated).length === 0 || deduplicated.type === "unknown") return undefined;
  return deduplicated;
};

const operationTypes = (operation: Operation, onReference: ReferenceSink): OperationTypes => {
  const { header, path, query } = operation.parameters;
  const dataRequired: Array<string> = [];
  if (operation.body?.required) dataRequired.push("body");
  const properties: Record<string, Ir> = {
    body: operation.body?.schema ?? { type: "never" },
  };
  if (header.length > 0) {
    properties["headers"] = parametersToIr(header);
    if (header.some((parameter) => parameter.required)) dataRequired.push("headers");
  }
  properties["path"] = path.length > 0 ? parametersToIr(path) : { type: "never" };
  if (path.some((parameter) => parameter.required)) dataRequired.push("path");
  properties["query"] = query.length > 0 ? parametersToIr(query) : { type: "never" };
  if (query.some((parameter) => parameter.required)) dataRequired.push("query");
  properties["url"] = { const: operation.path, type: "string" };
  dataRequired.push("url");

  const names = {
    data: withSuffix(operation.id, "Data"),
    errors: withSuffix(operation.id, "Errors"),
    error: withSuffix(operation.id, "Error"),
    responses: withSuffix(operation.id, "Responses"),
    response: withSuffix(operation.id, "Response"),
  };
  const declarations = [
    typeAlias(
      names.data,
      schemaToType({ type: "object", properties, required: dataRequired }, onReference),
      [],
      false,
      true,
    ),
  ];

  const errors: Record<string, Ir> = {};
  const successes: Record<string, Ir> = {};
  for (const [status, schema] of Object.entries(operation.responses)) {
    if (status.startsWith("2")) successes[status] = schema;
    else if (status.startsWith("4") || status.startsWith("5")) errors[status] = schema;
  }

  let errorsName: string | undefined;
  let errorName: string | undefined;
  if (Object.keys(errors).length > 0) {
    errorsName = names.errors;
    declarations.push(
      typeAlias(
        names.errors,
        schemaToType(
          { type: "object", properties: errors, required: Object.keys(errors) },
          onReference,
        ),
        [],
      ),
    );
    if (responseUnion(Object.values(errors)) !== undefined) {
      errorName = names.error;
      declarations.push(typeAlias(names.error, { kind: "indexedAccess", name: names.errors }, []));
    }
  }
  let responsesName: string | undefined;
  let responseName: string | undefined;
  if (Object.keys(successes).length > 0) {
    responsesName = names.responses;
    declarations.push(
      typeAlias(
        names.responses,
        schemaToType(
          { type: "object", properties: successes, required: Object.keys(successes) },
          onReference,
        ),
        [],
      ),
    );
    if (responseUnion(Object.values(successes)) !== undefined) {
      responseName = names.response;
      declarations.push(
        typeAlias(names.response, { kind: "indexedAccess", name: names.responses }, []),
      );
    }
  }
  return {
    names: {
      data: names.data,
      errors: errorsName,
      error: errorName,
      responses: responsesName,
      response: responseName,
    },
    declarations,
  };
};

const clientOptionsType = (servers: ReadonlyArray<string>): TypeNode => {
  const baseUrl =
    servers.length === 0
      ? keyword("string")
      : union([
          ...servers.map((url) => literal(url)),
          { kind: "intersection", members: [keyword("string"), { kind: "object", members: [] }] },
        ]);
  return {
    kind: "object",
    members: [{ kind: "property", name: "baseUrl", optional: false, doc: [], type: baseUrl }],
  };
};

const renderTypes = (
  parsed: ParsedDocument,
  schemas: ReadonlyArray<SchemaEmission>,
): { source: string; operations: ReadonlyMap<Operation, OperationTypeNames> } => {
  const declarations = [typeAlias("ClientOptions", clientOptionsType(parsed.servers), [])];
  const exported = new Set(["ClientOptions"]);
  const componentNames = new Set(schemas.map(({ name }) => componentTypeName(name)));
  const onReference: ReferenceSink = (name) => {
    if (!componentNames.has(name)) throw new Error(`Reference to undeclared schema ${name}`);
  };
  const declare = (name: string) => {
    if (exported.has(name)) throw new Error(`Generated type name ${name} is declared twice`);
    exported.add(name);
  };
  for (const { name, schema, write } of schemas) {
    const typeName = assertName(componentTypeName(name), reservedTypeNames, "Schema");
    declare(typeName);
    declarations.push(
      typeAlias(typeName, schemaToType(schema, onReference), schemaComment(schema), true, write),
    );
  }
  const operations = new Map<Operation, OperationTypeNames>();
  for (const operation of parsed.operations) {
    const types = operationTypes(operation, onReference);
    for (const name of Object.values(types.names)) if (name !== undefined) declare(name);
    operations.set(operation, types.names);
    declarations.push(...types.declarations);
  }
  return { source: `${GENERATED_HEADER}\n\n${declarations.join("\n\n")}\n`, operations };
};

