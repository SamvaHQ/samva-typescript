import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

import { type OpenApiDocument, readPublicOpenApi } from "@samva/openapi/document";
import { type JsonSchema, Predicate, Schema, SchemaRepresentation } from "effect";

import { compilePredicates } from "./compile-predicates";
import { expandSchemaObjects } from "./expand-schema-objects";

const root = resolve(import.meta.dirname, "..");
const check = process.argv.includes("--check");

type JsonObject = { readonly [key: string]: Schema.Json };

const isObject = (value: Schema.Json | undefined): value is JsonObject =>
  Predicate.isObject(value) && !Array.isArray(value);

/** The signed body schema of every event in the document's `webhooks` section, in document order. */
const eventSchemas = (document: OpenApiDocument): ReadonlyArray<[string, JsonObject]> => {
  const { webhooks } = document;
  if (!isObject(webhooks)) throw new Error("The public OpenAPI document has no webhooks section");
  return Object.entries(webhooks).map(([type, pathItem]) => {
    const post = isObject(pathItem) ? pathItem.post : undefined;
    const requestBody = isObject(post) ? post.requestBody : undefined;
    const content = isObject(requestBody) ? requestBody.content : undefined;
    const json = isObject(content) ? content["application/json"] : undefined;
    const schema = isObject(json) ? json.schema : undefined;
    if (!isObject(schema)) throw new Error(`Webhook ${type} has no application/json body schema`);
    return [type, schema];
  });
};

const events = eventSchemas(readPublicOpenApi()).map(([type, schema]) => {
  const name =
    type
      .split(/[._]/)
      .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
      .join("") + "Event";
  // The document inlines every definition; signed envelopes and payloads may gain additive fields.
  const document: JsonSchema.Document<"draft-2020-12"> = {
    dialect: "draft-2020-12",
    schema,
    definitions: {},
  };
  const represented = SchemaRepresentation.toRepresentation(
    SchemaRepresentation.fromJsonSchemaDocument(document, { patterns: "apply" }).ast,
    { referencePolicy: () => undefined },
  );
  const code = SchemaRepresentation.toCodeDocument(
    SchemaRepresentation.toMultiDocument(represented),
  );
  const [generated] = code.codes;
  if (
    generated === undefined ||
    code.codes.length > 1 ||
    code.references.nonRecursives.length ||
    Object.keys(code.references.recursives).length ||
    code.artifacts.length
  ) {
    throw new Error(`Unexpected references or artifacts in ${type}`);
  }
  return { type, name, document, generated };
});
const header =
  "// @generated by scripts/generate.ts from the webhooks section of the public OpenAPI document (@samva/openapi). Do not edit.\n";
const jsonType =
  "export type JsonValue = null | boolean | number | string | ReadonlyArray<JsonValue> | { readonly [key: string]: JsonValue };\n";
const types =
  header +
  jsonType +
  events
    .map(
      ({ name, generated }) =>
        `export type ${name} = ${generated.Type.replaceAll("Schema.Json", "JsonValue")};\nexport type ${name.replace(/Event$/, "Payload")} = ${name}["data"];`,
    )
    .join("\n") +
  `\nexport type SamvaWebhookEvent = ${events.map(({ name }) => name).join(" | ")};\nexport interface UnknownWebhookEvent { readonly type: string; readonly timestamp: string; readonly data: unknown; }\nexport type WebhookEvent = SamvaWebhookEvent | UnknownWebhookEvent;\nexport type WebhookEventType = SamvaWebhookEvent["type"];\nexport type WebhookPayload<Type extends WebhookEventType> = Extract<SamvaWebhookEvent, { readonly type: Type }>["data"];\n`;
const schemas =
  header +
  'import { Schema } from "effect";\n' +
  events
    .map(
      ({ name, generated }) =>
        `export const ${name}Schema = ${generated.runtime.replaceAll("Schema.Number", "Schema.Finite")};`,
    )
    .join("\n") +
  `\nexport const SamvaWebhookEventSchema = Schema.Union([${events.map(({ name }) => name + "Schema").join(", ")}]);\n`;
const jsonSchemas =
  header +
  'import type { WebhookEventType } from "./types.gen.js";\n' +
  `export const WebhookEventJsonSchemas: Readonly<Record<WebhookEventType, Readonly<Record<string, unknown>>>> = ${JSON.stringify(Object.fromEntries(events.map(({ type, document }) => [type, document.schema])))};\n`;
const predicates = compilePredicates();
const cases = events.map(({ type, document }) => {
  const predicate = predicates.compile(document.schema, document.definitions);
  return `case ${JSON.stringify(type)}: return ${predicate}(value);`;
});
const decoder =
  header +
  'import type { SamvaWebhookEvent, WebhookEvent } from "./types.gen.js";\n' +
  predicates.source() +
  `
/** Narrow an event to a structurally valid payload known to this package. */
export const isKnownEvent = (value: WebhookEvent): value is SamvaWebhookEvent => {
  switch (value.type) {
    ${cases.join("\n")}
    default: return false;
  }
};
export const validateEvent = (value: unknown): value is WebhookEvent => {
  if (!isObject(value) || typeof value.type !== "string" || typeof value.timestamp !== "string" || !Object.hasOwn(value, "data")) return false;
  switch (value.type) {
    ${cases.join("\n")}
    default: return true;
  }
};
`;
const outputs = new Map([
  ["src/types.gen.ts", types],
  ["src/schemas.gen.ts", expandSchemaObjects(schemas)],
  ["src/json-schemas.gen.ts", jsonSchemas],
  ["src/decoder.gen.ts", decoder],
]);
for (const [path, source] of outputs) {
  const destination = resolve(root, path);
  if (check) {
    // Formatting is part of generation; compare the same formatted artifacts.
    const formatter = Bun.spawn(
      [
        "bun",
        "run",
        "oxfmt",
        `--config=${resolve(root, "../../oxfmt.config.ts")}`,
        `--stdin-filepath=${destination}`,
      ],
      { stdin: new Blob([source]), stdout: "pipe", stderr: "inherit" },
    );
    const formatted = await new Response(formatter.stdout).text();
    if ((await formatter.exited) !== 0) throw new Error(`Formatting failed: ${path}`);
    if ((await readFile(destination, "utf8")) !== formatted)
      throw new Error(`Stale generated webhook artifact: ${path}`);
  } else {
    await writeFile(destination, source);
  }
}
if (!check) {
  const paths = [...outputs.keys()].map((path) => resolve(root, path));
  await Bun.$`bun run oxfmt --config=${resolve(root, "../../oxfmt.config.ts")} ${paths}`;
}
